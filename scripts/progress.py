#!/usr/bin/env python3
"""The only way to change the state of a card.

State lives in tasks/<CARD-ID>/progress.json; tasks/<CARD-ID>/progress.md is regenerated from it
on every write, for people to read. Nobody edits either file by hand. Timestamps always come from
the system clock (UTC), status values are validated and the log is kept in order.

Usage:
  progress.py init     <CARD>
  progress.py start    <CARD> <STAGE>                      # status in-progress, attempts + 1
  progress.py set      <CARD> <STAGE> <done|blocked|failed> --note TEXT [--blocker TEXT | --blocker-file PATH]
  progress.py log      <CARD> <STAGE> --note TEXT
  progress.py card     <CARD> <in-progress|blocked|in-review|done> [--pr URL]
  progress.py show     <CARD>                              # print progress.md
  progress.py check    <CARD>                              # validate the state file
"""
import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STAGES = ["ba", "architect", "prep", "coder", "qa", "docs", "retrospective"]
STAGE_STATUS = {"pending", "in-progress", "done", "blocked", "failed"}
CARD_STATUS = {"in-progress", "blocked", "in-review", "done"}


def now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%MZ")


def paths(card: str) -> tuple[Path, Path]:
    folder = ROOT / "tasks" / card
    return folder / "progress.json", folder / "progress.md"


def load(card: str) -> dict:
    state_file, _ = paths(card)
    if not state_file.exists():
        sys.exit(f"progress: {state_file} does not exist; run 'init {card}' first")
    return json.loads(state_file.read_text(encoding="utf-8"))


def save(card: str, state: dict) -> None:
    state_file, md_file = paths(card)
    state_file.parent.mkdir(parents=True, exist_ok=True)
    state_file.write_text(json.dumps(state, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    md_file.write_text(render(state), encoding="utf-8")


def render(state: dict) -> str:
    lines = [f"# {state['card']} progress", "", "<!-- Generated by scripts/progress.py from progress.json. Do not edit. -->", "",
             f"Status: {state['status']}"]
    if state.get("pr"):
        lines.append(f"PR: {state['pr']}")
    lines += ["", "| Stage | Status | Attempts | Updated |", "|---|---|---|---|"]
    for s in state["stages"]:
        lines.append(f"| {s['name']} | {s['status']} | {s['attempts']} | {s['updated'] or ''} |")
    if state.get("blocker"):
        b = state["blocker"]
        lines += ["", "## Blocker", "", f"Stage: {b['stage']} ({b['ts']})", "", b["text"].rstrip()]
    lines += ["", "## Log"]
    lines += [f"- {e['ts']} {e['stage']}: {e['note']}" for e in state["log"]]
    return "\n".join(lines) + "\n"


def stage_of(state: dict, name: str) -> dict:
    for s in state["stages"]:
        if s["name"] == name:
            return s
    sys.exit(f"progress: unknown stage '{name}'. Stages: {', '.join(STAGES)}")


def add_log(state: dict, stage: str, note: str) -> str:
    ts = now()
    state["log"].append({"ts": ts, "stage": stage, "note": note.strip()})
    return ts


def cmd_init(a):
    state_file, _ = paths(a.card)
    if state_file.exists():
        sys.exit(f"progress: {state_file} already exists")
    state = {"card": a.card, "status": "in-progress", "pr": None, "blocker": None,
             "stages": [{"name": n, "status": "pending", "attempts": 0, "updated": None} for n in STAGES],
             "log": []}
    add_log(state, "intake", "card started")
    save(a.card, state)


def cmd_start(a):
    state = load(a.card)
    s = stage_of(state, a.stage)
    s["status"], s["attempts"] = "in-progress", s["attempts"] + 1
    s["updated"] = add_log(state, a.stage, f"attempt {s['attempts']} started")
    save(a.card, state)


def cmd_set(a):
    state = load(a.card)
    s = stage_of(state, a.stage)
    if a.status == "failed" and a.stage != "qa":
        sys.exit("progress: only qa can be 'failed'")
    blocker_text = a.blocker or (Path(a.blocker_file).read_text(encoding="utf-8") if a.blocker_file else None)
    if a.status == "blocked" and not blocker_text:
        sys.exit("progress: 'blocked' needs --blocker or --blocker-file with the questions for the user")
    s["status"] = a.status
    s["updated"] = add_log(state, a.stage, a.note)
    if a.status == "blocked":
        state["blocker"] = {"stage": a.stage, "ts": s["updated"], "text": blocker_text}
        state["status"] = "blocked"
    elif state.get("blocker") and state["blocker"]["stage"] == a.stage:
        state["blocker"] = None
        state["status"] = "in-progress"
    save(a.card, state)


def cmd_log(a):
    state = load(a.card)
    add_log(state, a.stage, a.note)
    save(a.card, state)


def cmd_card(a):
    state = load(a.card)
    state["status"] = a.status
    if a.pr:
        state["pr"] = a.pr
    add_log(state, "card", f"status {a.status}" + (f", PR {a.pr}" if a.pr else ""))
    save(a.card, state)


def cmd_show(a):
    print(render(load(a.card)), end="")


def cmd_check(a):
    state = load(a.card)
    errors = []
    if state["status"] not in CARD_STATUS:
        errors.append(f"card status '{state['status']}' is not one of {sorted(CARD_STATUS)}")
    for s in state["stages"]:
        if s["status"] not in STAGE_STATUS:
            errors.append(f"stage {s['name']}: status '{s['status']}' is not valid")
    times = [e["ts"] for e in state["log"]]
    if times != sorted(times):
        errors.append("log timestamps are not in order")
    if state["status"] == "blocked" and not state.get("blocker"):
        errors.append("card is blocked but has no blocker")
    _, md_file = paths(a.card)
    if md_file.read_text(encoding="utf-8") != render(state):
        errors.append("progress.md was edited by hand (it differs from progress.json)")
    if errors:
        print("\n".join(f"✖ {e}" for e in errors), file=sys.stderr)
        sys.exit(1)
    print("ok")


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    sub.add_parser("init").add_argument("card")
    for name in ("start",):
        sp = sub.add_parser(name); sp.add_argument("card"); sp.add_argument("stage")
    sp = sub.add_parser("set"); sp.add_argument("card"); sp.add_argument("stage")
    sp.add_argument("status", choices=["done", "blocked", "failed"]); sp.add_argument("--note", required=True)
    g = sp.add_mutually_exclusive_group(); g.add_argument("--blocker"); g.add_argument("--blocker-file")
    sp = sub.add_parser("log"); sp.add_argument("card"); sp.add_argument("stage"); sp.add_argument("--note", required=True)
    sp = sub.add_parser("card"); sp.add_argument("card"); sp.add_argument("status", choices=sorted(CARD_STATUS))
    sp.add_argument("--pr")
    sub.add_parser("show").add_argument("card")
    sub.add_parser("check").add_argument("card")
    a = p.parse_args()
    globals()[f"cmd_{a.cmd}"](a)


if __name__ == "__main__":
    main()
